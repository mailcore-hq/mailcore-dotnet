def pascal(nome: str) -> str:
    return ''.join(parte[:1].upper() + parte[1:] for parte in nome.split('_'))


def camel(nome: str) -> str:
    resultado = pascal(nome)
    return resultado[:1].lower() + resultado[1:]


def literal(valor: str) -> str:
    return '"' + valor.replace('\\', '\\\\').replace('"', '\\"') + '"'


def rota(caminho: str) -> str:
    def segmento(encontrado):
        return '{Caminho.Segmento(' + camel(encontrado.group(1)) + ')}'
    caminho = re.sub(r'#\{segmento\((\w+)\)\}', segmento, caminho)
    caminho = caminho.replace('#{indice}', '{Caminho.Indice(indice)}')
    return ('$' if '{Caminho.' in caminho else '') + literal(caminho)


def tipo(parametro: dict, metodo: dict) -> str:
    nome = parametro['nome']
    if nome == 'indice':
        return 'int'
    if metodo['consulta'] == nome:
        return 'IReadOnlyDictionary<string, object?>?'
    if '#{segmento(' + nome + ')}' in metodo['caminho'] or nome == 'segmento_id':
        return 'string'
    return 'object'


def corpo(classe: str, metodo: dict) -> tuple[str, str]:
    valor = metodo['corpo']
    if valor is None:
        return 'null', 'Nenhum'
    compostos = {
        '{ segmento_id: segmento_id }': 'new Dictionary<string, object?> { ["segmento_id"] = segmentoId }',
        '{ topicos: topicos }': 'new Dictionary<string, object?> { ["topicos"] = topicos }',
        '{ ids: ids }': 'new Dictionary<string, object?> { ["ids"] = ids }',
    }
    valor = compostos.get(valor, camel(valor))
    forma = 'Lista' if classe == 'Lotes' and metodo['nome'] == 'enviar' else 'Objeto'
    return valor, forma


def emitir_metodo(classe: str, metodo: dict) -> str:
    argumentos = []
    for parametro in metodo['parametros']:
        argumento = tipo(parametro, metodo) + ' ' + camel(parametro['nome'])
        if parametro['opcional'] and metodo['consulta'] == parametro['nome']:
            argumento += ' = null'
        argumentos.append(argumento)
    if metodo['fluxo']:
        argumentos.append('Func<ReadOnlyMemory<byte>, CancellationToken, ValueTask> consumir')
    argumentos += ['OpcoesRequisicao? opcoes = null', 'CancellationToken cancelamento = default']
    descricao = 'Executa a operação ' + metodo['nome'] + ' do contrato público Mailcore.'
    if classe == 'Emails' and metodo['nome'] == 'enviar':
        descricao = 'Aceita a intenção de envio; acompanhe a entrega pelos eventos.'
    elif metodo['fluxo']:
        descricao = 'Entrega blocos ao consumidor sem acumular o download na resposta.'
    linhas = ['    /// <summary>' + descricao + '</summary>',
              '    public Task<Resposta> ' + pascal(metodo['nome']) + 'Async(',
              '        ' + ',\n        '.join(argumentos) + ')',
              '    {',
              '        return _transporte.ExecutarAsync(',
              '            HttpMethod.' + metodo['verbo'].capitalize() + ',']
    if metodo['fluxo']:
        linhas += ['            () =>', '            {',
                   '                if (consumir is null)',
                   '                {',
                   '                    throw ErroMailcore.Configuracao("Informe um consumidor para o download.");',
                   '                }',
                   '', '                return ' + rota(metodo['caminho']) + ';',
                   '            },']
    else:
        linhas += ['            () => ' + rota(metodo['caminho']) + ',']
    valor, forma = corpo(classe, metodo)
    linhas += ['            ' + valor + ',',
               '            FormatoCorpo.' + forma + ',',
               '            ' + (camel(metodo['consulta']) if metodo['consulta'] else 'null') + ',',
               '            FormatoResposta.' + {'json':'Json','texto':'Texto','bytes':'Bytes'}[metodo['formato']] + ',',
               '            ' + str(metodo['aceitar_vazio']).lower() + ',',
               '            opcoes,',
               '            cancelamento' + (',' if metodo['fluxo'] else ');')]
    if metodo['fluxo']:
        linhas += ['            consumir);']
    linhas += ['    }']
    opcionais_corpo = [p for p in metodo['parametros'] if p['opcional'] and metodo['consulta'] != p['nome']]
    if opcionais_corpo:
        obrigatorios = [p for p in metodo['parametros'] if p not in opcionais_corpo]
        argumentos_conveniencia = [tipo(p, metodo) + ' ' + camel(p['nome']) for p in obrigatorios]
        argumentos_conveniencia += ['CancellationToken cancelamento = default']
        encaminhados = [camel(p['nome']) for p in obrigatorios]
        encaminhados += ['new Dictionary<string, object?>()', 'null', 'cancelamento']
        linhas += ['', '    /// <summary>Usa um objeto vazio para o corpo opcional da operação.</summary>',
                   '    public Task<Resposta> ' + pascal(metodo['nome']) + 'Async(',
                   '        ' + ',\n        '.join(argumentos_conveniencia) + ')',
                   '    {', '        return ' + pascal(metodo['nome']) + 'Async(' + ', '.join(encaminhados) + ');',
                   '    }']
    return '\n'.join(linhas)


def emitir_classe(classe: dict) -> str:
    metodos = classe['metodos']
    precisa_dict = any(m['consulta'] or (m['corpo'] or '').startswith('{ ') or any(p['opcional'] and m['consulta'] != p['nome'] for p in m['parametros']) for m in metodos)
    linhas = ['// Gerado por scripts/gerar_recursos.py a partir das operações públicas Mailcore.']
    if any(m['fluxo'] for m in metodos):
        linhas += ['using System;']
    if precisa_dict:
        linhas += ['using System.Collections.Generic;']
    if metodos:
        linhas += ['using System.Net.Http;', 'using System.Threading;', 'using System.Threading.Tasks;']
    linhas += ['using Mailcore.Interno;', '', 'namespace Mailcore.Recursos;', '',
               '/// <summary>Operações de ' + classe['modulo'] + ' no contrato público Mailcore.</summary>',
               'public sealed class ' + classe['modulo'], '{']
    if metodos:
        linhas += ['    private readonly Transporte _transporte;', '']
    for nome, filho in classe['filhos'].items():
        linhas += ['    /// <summary>Retorna as operações de ' + nome + '.</summary>',
                   '    public ' + filho + ' ' + pascal(nome) + ' { get; }', '']
    linhas += ['    internal ' + classe['modulo'] + '(Transporte transporte)', '    {']
    if metodos:
        linhas += ['        _transporte = transporte;']
    for nome, filho in classe['filhos'].items():
        linhas += ['        ' + pascal(nome) + ' = new ' + filho + '(transporte);']
    linhas += ['    }']
    for metodo in metodos:
        linhas += ['', emitir_metodo(classe['modulo'], metodo)]
    linhas += ['}', '']
    return '\n'.join(linhas)


def fontes() -> dict[str, str]:
    return {'src/Mailcore/Recursos/' + classe['modulo'] + '.cs': emitir_classe(classe) for classe in ESPECIFICACAO}


def main() -> None:
    argumentos = argparse.ArgumentParser(description=__doc__)
    argumentos.add_argument('--verificar', action='store_true', help='Confere as fontes sem alterá-las.')
    opcoes = argumentos.parse_args()
    raiz = Path(__file__).resolve().parents[1]
    divergencias = []
    for nome, conteudo in fontes().items():
        destino = raiz / nome
        if opcoes.verificar:
            if not destino.exists() or destino.read_text(encoding='utf-8') != conteudo:
                divergencias.append(nome)
        else:
            destino.parent.mkdir(parents=True, exist_ok=True)
            destino.write_text(conteudo, encoding='utf-8')
    if divergencias:
        raise SystemExit('Fontes divergentes: ' + ', '.join(divergencias))
    total = sum(len(classe['metodos']) for classe in ESPECIFICACAO)
    print(str(total) + ' operações C# conferidas.' if opcoes.verificar else 'Fontes C# preparadas.')


if __name__ == '__main__':
    main()
